def render_body(body):
    out, items = [], []
    def flush():
        nonlocal items
        if items:
            out.append("<ul>" + "".join(f"<li>{html.escape(i)}</li>" for i in items) + "</ul>")
            items = []
    for p in body:
        if p.startswith("• "):
            items.append(p[2:])
        else:
            flush()
            out.append(f"<p>{html.escape(p)}</p>")
    flush()
    return "\n".join(out)

def page(title, intro, secs, active):
    nav = lambda href, label, key: f'<a href="{href}"' + (' class="on"' if key == active else "") + f">{label}</a>"
    sections = "\n".join(f"<h2>{html.escape(h)}</h2>\n{render_body(b)}" for h, b in secs)
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Soapy {title}</title>
<meta name="color-scheme" content="dark">
<style>{CSS}</style></head>
<body><div class="wrap">
<div class="brand"><img src="icon.png" alt=""><b>Soapy</b></div>
<nav>{nav("privacy.html", "Privacy Policy", "privacy")}{nav("terms.html", "Terms of Use", "terms")}</nav>
<h1>{title}</h1>
<p class="upd">Last updated: {c.UPDATED}</p>
<div class="intro">{html.escape(intro)}</div>
{sections}
<footer>Soapy is made by {html.escape(c.DEVELOPER)}.</footer>
</div></body></html>
"""

